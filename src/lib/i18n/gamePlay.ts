/** a plural-aware string: `tp()` picks the category (Intl.PluralRules) and
 *  fills {count}. `other` always exists; the rest fill in where a language
 *  needs them (Arabic uses up to six; most need only one and other). */
export interface Plural {
  zero?: string;
  one?: string;
  two?: string;
  few?: string;
  many?: string;
  other: string;
}

